package store

import (
	"context"
	"time"

	"github.com/shubhamkr585/relay/internal/domain"
)

// EnqueueParams contains input arguments for enqueuing a job.
type EnqueueParams struct {
	Queue          string
	Payload        []byte
	Priority       uint32
	Delay          time.Duration
	IdempotencyKey string
	MaxAttempts    uint32
	JobID          string // Optional: pre-generated by Raft leader for determinism
	RunAt          int64  // Optional: pre-calculated by Raft leader (UnixNano)
}

// Config specifies storage and batching engine options.
type Config struct {
	// Path to the BBolt database file.
	Path string

	// NoSync controls whether BBolt calls fsync after every commit.
	// Production systems MUST set NoSync = false (durability guaranteed).
	// Benchmarks can set NoSync = true to isolate CPU/memory overhead.
	NoSync bool

	// BatchWindow is the maximum duration to wait while grouping concurrent writes.
	// Default is 2ms per spec.
	BatchWindow time.Duration

	// BatchMaxSize is the maximum number of operations to group into a single commit.
	// Default is 64 per spec.
	BatchMaxSize int

	// ReaperInterval is the frequency of the background lease reaper ticker.
	// Default is 50ms.
	ReaperInterval time.Duration

	// BaseBackoff and MaxBackoff for retry calculations.
	BaseBackoff time.Duration
	MaxBackoff  time.Duration

	// Clock provides time abstraction. If nil, realClock{} is used.
	Clock Clock
}

// DefaultConfig provides production-grade defaults.
func DefaultConfig(path string) Config {
	return Config{
		Path:           path,
		NoSync:         false, // fsync enabled by default
		BatchWindow:    2 * time.Millisecond,
		BatchMaxSize:   64,
		ReaperInterval: 50 * time.Millisecond,
		BaseBackoff:    domain.DefaultBaseDelay,
		MaxBackoff:     domain.DefaultMaxDelay,
		Clock:          realClock{},
	}
}

// Engine defines the primary interface for durable job storage.
type Engine interface {
	// Enqueue adds a new job or returns an existing one if the idempotency key matches.
	Enqueue(ctx context.Context, params *EnqueueParams) (*domain.Job, bool, error)

	// Reserve leases the highest priority ready job for the given queue.
	// Returns ErrQueueEmpty / ErrNotFound if no ready job exists.
	Reserve(ctx context.Context, queue, workerID string, leaseDuration time.Duration) (*domain.Job, string, error)

	// Ack marks a leased job as DONE, fenced by leaseToken.
	Ack(ctx context.Context, jobID, leaseToken string) error

	// Nack releases a leased job back to PENDING (with backoff) or DEAD (if max attempts reached).
	Nack(ctx context.Context, jobID, leaseToken, errorMsg string, retryAfter time.Duration) error

	// ExtendLease increases the lease expiration time for an actively leased job.
	ExtendLease(ctx context.Context, jobID, leaseToken string, extraDuration time.Duration) (int64, error)

	// Stats returns aggregate counts for the queue across all states.
	Stats(ctx context.Context, queue string) (*domain.QueueStats, error)

	// ListDead returns up to limit jobs currently in DEAD state (DLQ).
	ListDead(ctx context.Context, queue string, limit uint32) ([]*domain.Job, error)

	// RequeueDead moves a job from DEAD back to PENDING, resetting attempts to 0.
	RequeueDead(ctx context.Context, jobID string) (*domain.Job, error)

	// GetJob retrieves a job by ID.
	GetJob(ctx context.Context, jobID string) (*domain.Job, error)

	// Close flushes all pending operations and closes the database.
	Close() error
}
